"""Run the full J4 verification: reference kernel suite + failure-path suite.

Usage: python3 tests/failure_paths/run_all.py [--evidence PATH]
Writes the combined output to evidence/failure-path-results.txt by default.
Exit code is nonzero if any test fails.
"""
import io
import os
import sys
import unittest

_HERE = os.path.dirname(os.path.abspath(__file__))
_WORKTREE = os.path.abspath(os.path.join(_HERE, '..', '..'))
sys.path.insert(0, os.path.join(_WORKTREE, 'packages', 'kernel'))
sys.path.insert(0, _HERE)


def main():
    evidence = os.path.join(_WORKTREE, 'evidence', 'failure-path-results.txt')
    if '--evidence' in sys.argv:
        evidence = sys.argv[sys.argv.index('--evidence') + 1]

    loader = unittest.TestLoader()
    suite = unittest.TestSuite()
    suite.addTests(loader.loadTestsFromName('test_kernel'))
    suite.addTests(loader.discover(_HERE, pattern='test_*.py'))

    buf = io.StringIO()
    runner = unittest.TextTestRunner(stream=buf, verbosity=1)
    result = runner.run(suite)
    output = buf.getvalue()

    header = (
        '# J4 failure-path verification results\n'
        '# Generated by tests/failure_paths/run_all.py. Do not hand-edit.\n'
        f'# kernel tests: 24 reference tests; failure-path tests: '
        f'{result.testsRun - 24}\n\n'
    )
    with open(evidence, 'w') as fh:
        fh.write(header + output)
    print(output)
    print(f'wrote {evidence}')
    sys.exit(0 if result.wasSuccessful() else 1)


if __name__ == '__main__':
    main()
